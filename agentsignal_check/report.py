"""Markdown report with fix links."""
import datetime
from .links import SITE, fix_url, WHY_OAI
FIX = {
    "baseline": ("Side effect runs before/with interrupt() in the same node; LangGraph re-runs the whole node on resume.",
                 fix_url("baseline")),
    "double_execution.kill_resume": ("A crash right after the effect re-runs it on resume.",
                 fix_url("baseline")),
    "double_execution.kill_before_checkpoint": ("Crash between the effect and the checkpoint write re-runs the effect (cf. langchain-ai/langgraph#8039).",
                 fix_url("baseline")),
    "approval.lost_on_restart": ("Pending approvals don't survive a process restart -- use a durable checkpointer.",
                 f"{SITE}/templates/langgraph-human-in-the-loop/"),
    "approval.replay": ("Delivering the same approval twice (double-click, webhook retry, stale checkpoint) re-runs the effect.",
                 f"{SITE}/templates/langgraph-approval-ui/"),
}
ICON = {"PASS": "✅", "FAIL": "❌", "WARN": "⚠️", "SKIP": "➖", "ERROR": "💥"}

def render(report, target):
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    rs = report["results"]; fails = [r for r in rs if r["status"] == "FAIL"]
    out = [f"# agentsignal check report", "", f"- Target: `{target}`", f"- Framework: {report['framework']}",
           f"- Run at: {now}", f"- Verdict: **{'FAIL' if fails else 'PASS'}** ({len(fails)} failing of {len(rs)})", "",
           "| Detector | Status | Detail |", "|---|---|---|"]
    out += [f"| `{r['detector']}` | {ICON.get(r['status'], '')} {r['status']} | {r['detail'].replace('|', '/')} |" for r in rs]
    if fails:
        out += ["", "## How to fix", ""]
        for r in fails:
            why, _ = FIX.get(r["detector"], ("", SITE))
            if report.get("framework") == "openai-agents": why = WHY_OAI.get(r["detector"], why)
            url = fix_url(r["detector"], report.get("framework"))
            out.append(f"- **{r['detector']}**: {why} Pattern: {url}")
        out += ["", f"Want it fixed for you? **[$79 Fix]({SITE}/fix/)**: a tested patch for your approval flow within 48 hours, with a short test log, or a full refund. "
                f"Or get every tested template + updates with **[Signal Pro]({SITE}/pricing/)**."]
    out += ["", f"_Generated by [agentsignal-check](https://github.com/MounirMeziani/agentsignal-check) · {SITE}_", ""]
    return "\n".join(out)
